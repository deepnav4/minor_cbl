"use client";
import Link from "next/link";
import { notFound, useRouter } from "next/navigation";
import { use } from "react";
import { ProficiencyChart, QuadrantTrendChart } from "@/components/charts";
import { formatDate, Loading, ProgressBar, QuadrantBar, QuadrantLegend, Stat } from "@/components/ui";
import { formatDuration, subjectProficiency, topicStandings } from "@/lib/cbl";
import { useStore } from "@/lib/store";

export default function SubjectDashboard({
  params,
  searchParams,
}: {
  params: Promise<{ id: string }>;
  searchParams: Promise<{ thanks?: string }>;
}) {
  const { id } = use(params);
  const { thanks } = use(searchParams);
  const state = useStore();
  const router = useRouter();
  if (!state) return <Loading />;

  const subject = state.subjects.find((s) => s.id === id);
  if (!subject) notFound();

  const reports = state.reports.filter((r) => r.subjectId === id);
  const studiedIds = state.studied[id] ?? [];
  const standings = topicStandings(subject, reports, studiedIds);
  const proficiency = subjectProficiency(standings);
  const ranked = reports.length > 0;
  const studyPct = subject.pages.length ? Math.round((studiedIds.length / subject.pages.length) * 100) : 0;
  const thanksReport = thanks ? reports.find((r) => r.id === thanks) : undefined;
  const ready = subject.status === "ready";

  const trend = reports.map((r, i) => ({ label: `#${i + 1}`, proficiency: r.proficiency, accuracy: r.accuracy }));
  const quadTrend = reports.map((r, i) => ({ label: `#${i + 1}`, ...r.quadrants }));
  const leftToStudy = subject.topics.filter((t) => {
    const pages = subject.pages.filter((p) => p.topicId === t.id);
    return pages.some((p) => !studiedIds.includes(p.id));
  });

  return (
    <>
      {thanksReport ? (
        <div className="banner banner-success">
          <strong>Thanks for completing the quiz!</strong> Your report is ready: {thanksReport.proficiency}% proficiency, {thanksReport.accuracy}% accuracy.{" "}
          <Link href={`/reports/${thanksReport.id}`}>View detailed report →</Link>
        </div>
      ) : null}

      <div className="page-head">
        <div>
          <div className="small muted">
            <Link href="/">Dashboard</Link> / {subject.name}
          </div>
          <h1 style={{ marginTop: 4 }}>{subject.name}</h1>
          <p>
            {subject.source.type === "pdf" ? "Generated from PDF" : "Generated from syllabus image"} · {subject.source.filename} · added{" "}
            {formatDate(subject.createdAt)}
          </p>
        </div>
        <div className="row">
          <Link href={ready ? `/subjects/${id}/study` : "#"} className="btn" aria-disabled={!ready}>
            Just study
          </Link>
          <Link href={ready ? `/subjects/${id}/quiz` : "#"} className="btn btn-primary" aria-disabled={!ready}>
            {ranked ? "Take a quiz" : "Take diagnostic test"}
          </Link>
        </div>
      </div>

      {!ready ? (
        <div className="banner banner-info">
          <strong>Content is being prepared.</strong> Study pages and the question bank for this subject are generated by the AI service,
          which comes in phase 2. Until then, use the demo subjects to explore the app.
        </div>
      ) : !ranked ? (
        <div className="banner banner-info">
          <strong>No rankings yet.</strong> Take one diagnostic test so we can measure what you know <em>and how sure you are</em>. After
          that, topics are ranked and every new quiz targets your weak spots.
        </div>
      ) : null}

      <div className="grid grid-4" style={{ marginBottom: 16 }}>
        <Stat label="Proficiency" value={proficiency === null ? "—" : `${proficiency}%`} sub={ranked ? "mean of tested topics" : "not ranked yet"} />
        <Stat label="Study progress" value={`${studyPct}%`} sub={`${studiedIds.length} of ${subject.pages.length} pages`} />
        <Stat label="Quizzes taken" value={reports.length} sub={ranked ? `last on ${formatDate(reports[reports.length - 1].createdAt)}` : "—"} />
        <Stat
          label="Misinformed answers"
          value={ranked ? reports[reports.length - 1].quadrants.misinformed : "—"}
          sub="in the latest quiz (confidently wrong)"
        />
      </div>

      <div className="card" style={{ marginBottom: 16 }}>
        <div className="card-head">
          <div>
            <h2>Topic rankings</h2>
            <p>
              {ranked
                ? "Ordered by priority: weak and confidently-wrong topics first, with a small boost for content you haven't studied"
                : "Rankings appear after your first test"}
            </p>
          </div>
          {ranked ? <QuadrantLegend /> : null}
        </div>
        <div className="table-wrap">
          <table className="table">
            <thead>
              <tr>
                <th style={{ width: 40 }}>#</th>
                <th>Topic</th>
                <th style={{ width: "22%" }}>Proficiency</th>
                <th style={{ width: "20%" }}>Last result</th>
                <th style={{ width: "14%" }}>Studied</th>
                <th>Status</th>
              </tr>
            </thead>
            <tbody>
              {standings.map((t, i) => (
                <tr key={t.topicId}>
                  <td className="muted">{ranked ? i + 1 : "—"}</td>
                  <td><strong>{t.name}</strong></td>
                  <td>
                    {t.proficiency === null ? (
                      <span className="muted small">Not tested</span>
                    ) : (
                      <div className="row" style={{ flexWrap: "nowrap" }}>
                        <div style={{ flex: 1 }}><ProgressBar value={t.proficiency} /></div>
                        <span className="small" style={{ width: 36, textAlign: "right" }}>{t.proficiency}%</span>
                      </div>
                    )}
                  </td>
                  <td>{t.latest ? <QuadrantBar counts={t.latest.quadrants} /> : <span className="muted small">—</span>}</td>
                  <td className="small">{Math.round(t.studied * 100)}%</td>
                  <td>
                    {t.proficiency === null ? (
                      <span className="badge">Untested</span>
                    ) : t.latest && t.latest.quadrants.misinformed > 0 ? (
                      <span className="badge q-misinformed">Fix misconceptions</span>
                    ) : t.proficiency >= 80 ? (
                      <span className="badge q-mastery">Mastered</span>
                    ) : t.proficiency >= 50 ? (
                      <span className="badge q-doubt">Building</span>
                    ) : (
                      <span className="badge q-uninformed">Needs work</span>
                    )}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>

      {ranked ? (
        <div className="grid grid-2" style={{ marginBottom: 16 }}>
          <div className="card">
            <div className="card-head">
              <div>
                <h2>Improvement</h2>
                <p>Proficiency vs plain accuracy per quiz</p>
              </div>
            </div>
            <ProficiencyChart
              data={trend}
              series={[
                { key: "proficiency", name: "Proficiency (confidence-weighted)" },
                { key: "accuracy", name: "Accuracy" },
              ]}
            />
          </div>
          <div className="card">
            <div className="card-head">
              <div>
                <h2>Knowledge quadrants</h2>
                <p>How your answers moved between quadrants</p>
              </div>
            </div>
            <QuadrantTrendChart data={quadTrend} />
          </div>
        </div>
      ) : null}

      <div className="grid grid-2">
        <div className="card">
          <div className="card-head">
            <div>
              <h2>Evaluation reports</h2>
              <p>Click a report to see every answer</p>
            </div>
          </div>
          {reports.length ? (
            <table className="table table-click">
              <thead>
                <tr>
                  <th>Date</th>
                  <th>Type</th>
                  <th>Proficiency</th>
                  <th>Time</th>
                </tr>
              </thead>
              <tbody>
                {[...reports].reverse().map((r) => (
                  <tr key={r.id} onClick={() => router.push(`/reports/${r.id}`)}>
                    <td>{formatDate(r.createdAt)}</td>
                    <td><span className="badge">{r.kind === "diagnostic" ? "Diagnostic" : "Practice"}</span></td>
                    <td><strong>{r.proficiency}%</strong></td>
                    <td className="small">{formatDuration(r.totalTimeSec)}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          ) : (
            <div className="empty">No reports yet.</div>
          )}
        </div>
        <div className="card">
          <div className="card-head">
            <div>
              <h2>Still to study</h2>
              <p>Topics with unread pages</p>
            </div>
            {ready ? <Link href={`/subjects/${id}/study`} className="small">Open study →</Link> : null}
          </div>
          {leftToStudy.length ? (
            <ul style={{ margin: 0, paddingLeft: 18 }}>
              {leftToStudy.map((t) => (
                <li key={t.id}>{t.name}</li>
              ))}
            </ul>
          ) : (
            <div className="empty">{ready ? "All content studied." : "No content yet."}</div>
          )}
        </div>
      </div>
    </>
  );
}
